import type { FieldModel, SchemaModel } from '@/lib/dbml/types'
import { claim, isJsIdentifier, jsDoc, jsKey, jsString, parseType, pascal, typeKind } from './shared'
import type { TypeKind } from './shared'

/* SchemaModel → TypeScript row interfaces, and → Zod schemas. One type per
   table, keyed by column name, with nullable columns typed `T | null`. */

const TS_TYPE: Record<TypeKind, string> = {
  int: 'number',
  bigint: 'number',
  float: 'number',
  decimal: 'number',
  string: 'string',
  uuid: 'string',
  bool: 'boolean',
  date: 'Date',
  datetime: 'Date',
  time: 'string',
  json: 'unknown',
  bytes: 'Uint8Array',
  unknown: 'unknown',
}

/** Names for each enum and table type, unique across the file. */
function typeNames(model: SchemaModel) {
  const used = new Set<string>()
  const name = (base: string, fallback: string) => {
    const p = pascal(base)
    return claim(isJsIdentifier(p) ? p : `${fallback}${p}`, used)
  }
  const enums = new Map(model.enums.map((e) => [e.name, name(e.schema ? `${e.schema}_${e.name}` : e.name, 'Enum')]))
  const tables = new Map(model.tables.map((t) => [t.id, name(t.schema ? `${t.schema}_${t.name}` : t.name, 'Table')]))
  return { enums, tables }
}

const nullable = (f: FieldModel) => !f.notNull && !f.pk

export function toTypeScript(model: SchemaModel): string {
  const names = typeNames(model)
  const out: string[] = ['// Generated by Schemasketch. One type per table, shaped like a row.']
  for (const e of model.enums) out.push('', `export type ${names.enums.get(e.name)} = ${e.values.map(jsString).join(' | ') || 'never'}`)
  const pkOf = (id: string) => model.tables.find((t) => t.id === id)?.indexes.find((i) => i.pk)?.columns ?? []
  for (const t of model.tables) {
    const pk = pkOf(t.id)
    out.push('', ...jsDoc(t.note), `export interface ${names.tables.get(t.id)} {`)
    for (const f of t.fields) {
      const { base, array } = parseType(f.type)
      let type = f.enumName && names.enums.has(f.enumName) ? names.enums.get(f.enumName)! : TS_TYPE[typeKind(base)]
      if (array) type = /^\w+$/.test(type) ? `${type}[]` : `(${type})[]`
      out.push(...jsDoc(f.note, '  '), `  ${jsKey(f.name)}: ${type}${nullable(f) && !pk.includes(f.name) ? ' | null' : ''}`)
    }
    out.push('}')
  }
  return `${out.join('\n')}\n`
}

function zodType(f: FieldModel, enumSchema: string | null): string {
  const { base, args, array } = parseType(f.type)
  let z: string
  if (enumSchema) z = enumSchema
  else {
    const length = /^\d+$/.test(args[0] ?? '') ? args[0] : null
    switch (typeKind(base)) {
      case 'int':
      case 'bigint':
        z = 'z.int()'
        break
      case 'float':
      case 'decimal':
        z = 'z.number()'
        break
      case 'string':
        z = length && (base === 'varchar' || base === 'char' || base === 'nvarchar' || base === 'nchar') ? `z.string().max(${length})` : 'z.string()'
        break
      case 'uuid':
        z = 'z.uuid()'
        break
      case 'bool':
        z = 'z.boolean()'
        break
      case 'date':
      case 'datetime':
        z = 'z.date()'
        break
      case 'time':
        z = 'z.string()'
        break
      case 'json':
        z = 'z.json()'
        break
      case 'bytes':
        z = 'z.instanceof(Uint8Array)'
        break
      default:
        z = 'z.unknown()'
    }
  }
  if (array) z = `z.array(${z})`
  return z
}

export function toZod(model: SchemaModel): string {
  const names = typeNames(model)
  const schemaName = (typeName: string) => `${typeName.charAt(0).toLowerCase()}${typeName.slice(1)}Schema`
  const out: string[] = ['// Generated by Schemasketch for Zod 4. One schema per table, shaped like a row.', "import * as z from 'zod'"]
  for (const e of model.enums) {
    const n = names.enums.get(e.name)!
    out.push('', `export const ${schemaName(n)} = z.enum([${e.values.map(jsString).join(', ')}])`, `export type ${n} = z.infer<typeof ${schemaName(n)}>`)
  }
  for (const t of model.tables) {
    const n = names.tables.get(t.id)!
    const pk = t.indexes.find((i) => i.pk)?.columns ?? []
    out.push('', ...jsDoc(t.note), `export const ${schemaName(n)} = z.object({`)
    for (const f of t.fields) {
      const enumName = f.enumName && names.enums.has(f.enumName) ? schemaName(names.enums.get(f.enumName)!) : null
      const z = zodType(f, enumName)
      out.push(...jsDoc(f.note, '  '), `  ${jsKey(f.name)}: ${z}${nullable(f) && !pk.includes(f.name) ? '.nullable()' : ''},`)
    }
    out.push('})', `export type ${n} = z.infer<typeof ${schemaName(n)}>`)
  }
  return `${out.join('\n')}\n`
}
