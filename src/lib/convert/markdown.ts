import type { FieldModel, IndexModel, SchemaModel, TableModel } from '@/lib/dbml/types'
import { toMermaid } from './mermaid'

/* SchemaModel → a Markdown data dictionary: every table, its columns, types,
   notes and relationships, with a Mermaid diagram at the top. */

/** Text safe inside a Markdown table cell. */
export const cell = (s: string) => s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>')

/** GitHub-style heading anchor. */
export const anchor = (s: string) =>
  s
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-')

const code = (s: string) => `\`${s.replace(/`/g, "'")}\``

function keyOf(t: TableModel, f: FieldModel, fks: Set<string>): string {
  const pkIndex = t.indexes.find((i) => i.pk)
  return [f.pk || pkIndex?.columns.includes(f.name) ? 'PK' : null, fks.has(f.name) ? 'FK' : null, f.unique && !f.pk ? 'unique' : null].filter(Boolean).join(', ')
}

function defaultOf(f: FieldModel): string {
  const parts = [f.increment ? 'auto increment' : null, f.defaultValue ? code(f.defaultValue.replace(/^`|`$/g, '')) : null].filter(Boolean)
  return parts.join(', ')
}

const indexLine = (i: IndexModel) =>
  `- ${i.columns.map(code).join(', ')}${[i.pk && 'primary key', i.unique && 'unique', i.type, i.name && `named ${code(i.name)}`].filter(Boolean).map((s) => `, ${s}`).join('')}`

const WORD = { one: 'one', 'zero-one': 'zero or one', many: 'many', 'zero-many': 'zero or many' } as const

export function toMarkdown(model: SchemaModel, opts: { title?: string; diagram?: boolean } = {}): string {
  const title = opts.title?.trim() || model.projectName || 'Schema'
  const out: string[] = [`# ${title}`, '']
  const facts = [
    `${model.tables.length} ${model.tables.length === 1 ? 'table' : 'tables'}`,
    `${model.refs.length} ${model.refs.length === 1 ? 'relationship' : 'relationships'}`,
    model.enums.length ? `${model.enums.length} ${model.enums.length === 1 ? 'enum' : 'enums'}` : null,
    model.databaseType ? `for ${model.databaseType}` : null,
  ].filter(Boolean)
  out.push(`Data dictionary: ${facts.join(', ')}. Generated by Schemasketch from the DBML.`, '')

  if (model.tables.length > 1) {
    out.push('## Tables', '')
    for (const t of model.tables) out.push(`- [${t.id}](#${anchor(t.id)})${t.note ? `: ${t.note.split('\n')[0]}` : ''}`)
    out.push('')
  }

  if (opts.diagram !== false && model.tables.length) {
    out.push('## Diagram', '', '```mermaid', toMermaid(model).trimEnd(), '```', '')
  }

  const byId = new Map(model.tables.map((t) => [t.id, t]))
  for (const t of model.tables) {
    const fks = new Set(model.refs.filter((r) => r.source.tableId === t.id).flatMap((r) => r.source.fields))
    out.push(`## ${t.id}`, '')
    if (t.note) out.push(t.note, '')
    const group = t.groupId ? model.groups.find((g) => g.id === t.groupId) : null
    if (group) out.push(`Group: ${group.name}`, '')

    out.push('| Column | Type | Key | Null | Default | Note |', '| --- | --- | --- | --- | --- | --- |')
    for (const f of t.fields) {
      const nullable = f.pk || f.notNull || t.indexes.some((i) => i.pk && i.columns.includes(f.name)) ? 'not null' : 'null'
      const type = f.enumName ? `${code(f.type)} (enum)` : code(f.type)
      out.push(`| ${cell(code(f.name))} | ${cell(type)} | ${keyOf(t, f, fks)} | ${nullable} | ${cell(defaultOf(f))} | ${cell(f.note ?? '')} |`)
    }
    out.push('')

    const extraIndexes = t.indexes.filter((i) => !(i.pk && i.columns.length === 1))
    if (extraIndexes.length) out.push('**Indexes**', '', ...extraIndexes.map(indexLine), '')

    const outgoing = model.refs.filter((r) => r.source.tableId === t.id)
    const incoming = model.refs.filter((r) => r.target.tableId === t.id && r.source.tableId !== t.id)
    if (outgoing.length) {
      out.push('**References**', '')
      for (const r of outgoing) {
        const target = byId.get(r.target.tableId)
        const actions = [r.onDelete && `on delete ${r.onDelete}`, r.onUpdate && `on update ${r.onUpdate}`].filter(Boolean)
        out.push(
          `- ${code(r.source.fields.join(', '))} → [${r.target.tableId}](#${anchor(r.target.tableId)}).${code(r.target.fields.join(', '))} (${WORD[r.source.cardinality]} to ${WORD[r.target.cardinality]}${actions.length ? `, ${actions.join(', ')}` : ''})${target ? '' : ' (table not found)'}`,
        )
      }
      out.push('')
    }
    if (incoming.length) {
      out.push('**Referenced by**', '')
      for (const r of incoming) out.push(`- [${r.source.tableId}](#${anchor(r.source.tableId)}).${code(r.source.fields.join(', '))}`)
      out.push('')
    }
  }

  if (model.enums.length) {
    out.push('## Enums', '')
    for (const e of model.enums) out.push(`### ${e.id}`, '', e.values.map(code).join(', '), '')
  }
  return `${out.join('\n').trimEnd()}\n`
}
