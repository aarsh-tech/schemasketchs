describe('Drizzle import', () => {
  it('reads a typical pg-core schema file', () => {
    const { model, warnings } = fromDrizzle(`import { relations, sql } from 'drizzle-orm'
import { pgTable, pgEnum, serial, text, integer, timestamp, uuid, varchar, index, uniqueIndex, type AnyPgColumn } from 'drizzle-orm/pg-core'

export const roleEnum = pgEnum('role', ['user', 'admin'])

/** people */
export const users = pgTable('users', {
  id: uuid('id').defaultRandom().primaryKey(),
  email: varchar('email', { length: 320 }).notNull().unique(),
  role: roleEnum().default('user').notNull(),
  settings: text('settings').$type<{ theme: 'dark' | 'light' }>(),
  createdAt: timestamp('created_at', { withTimezone: true, mode: 'string' }).defaultNow().notNull(),
  updatedAt: timestamp('updated_at').$onUpdate(() => new Date()),
  invitedBy: uuid('invited_by').references((): AnyPgColumn => users.id, { onDelete: 'set null' }),
})

export const posts = pgTable(
  'posts',
  (t) => ({
    id: t.integer().primaryKey().generatedAlwaysAsIdentity(),
    authorId: t.uuid('author_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
    slug: t.text().notNull(),
    title: t.varchar({ length: 200 }),
    score: t.integer().default(sql\`0\`),
    body: t.text().$defaultFn(() => crypto.randomUUID()),
  }),
  (table) => [
    uniqueIndex('posts_slug_idx').on(table.slug),
    index().on(table.authorId, sql\`lower(\${table.title})\`),
  ],
)

export const usersRelations = relations(users, ({ many }) => ({ posts: many(posts) }))
export type User = typeof users.$inferSelect
`)
    expect(model.databaseType).toBe('PostgreSQL')
    expect(model.enums).toEqual([{ id: 'role', name: 'role', schema: null, values: ['user', 'admin'] }])
    const [users, posts] = model.tables
    expect(users.fields.map((f) => [f.name, f.type, f.pk, f.notNull, f.defaultValue])).toEqual([
      ['id', 'uuid', true, false, '`gen_random_uuid()`'],
      ['email', 'varchar(320)', false, true, null],
      ['role', 'role', false, true, "'user'"],
      ['settings', 'text', false, false, null],
      ['created_at', 'timestamptz', false, true, '`now()`'],
      ['updated_at', 'timestamp', false, false, null],
      ['invited_by', 'uuid', false, false, null],
    ])
    expect(posts.fields.map((f) => [f.name, f.type, f.increment, f.defaultValue])).toEqual([
      ['id', 'integer', true, null],
      ['author_id', 'uuid', false, null],
      ['slug', 'text', false, null],
      ['title', 'varchar(200)', false, null],
      ['score', 'integer', false, '`0`'],
      ['body', 'text', false, null],
    ])
    expect(posts.indexes.map((i) => [i.name, i.unique, i.columns])).toEqual([
      ['posts_slug_idx', true, ['slug']],
      [null, false, ['author_id', '`lower(title)`']],
    ])
    expect(model.refs.map((r) => [r.source.tableId, r.source.fields, r.target.tableId, r.target.fields, r.onDelete])).toEqual([
      ['users', ['invited_by'], 'users', ['id'], 'set null'],
      ['posts', ['author_id'], 'users', ['id'], 'cascade'],
    ])
    expect(warnings).toEqual([])
  })

  it('reads mysql-core and sqlite-core tables', () => {
    const mysql = fromDrizzle(`import { mysqlTable, int, varchar, mysqlEnum } from 'drizzle-orm/mysql-core'
export const t = mysqlTable('things', {
  id: int('id').autoincrement().primaryKey(),
  kind: mysqlEnum('kind', ['a', 'b']).notNull(),
  name: varchar('name', { length: 50 }),
})`)
    expect(mysql.model.databaseType).toBe('MySQL')
    expect(mysql.model.enums).toEqual([{ id: 'things_kind', name: 'things_kind', schema: null, values: ['a', 'b'] }])
    expect(mysql.model.tables[0].fields.map((f) => `${f.name} ${f.type}${f.increment ? ' inc' : ''}`)).toEqual(['id int inc', 'kind things_kind', 'name varchar(50)'])

    const sqlite = fromDrizzle(`export const notes = sqliteTable('notes', {
  id: integer('id', { mode: 'number' }).primaryKey({ autoIncrement: true }),
  body: text('body').notNull(),
  done: integer('done', { mode: 'boolean' }).default(false),
})`)
    expect(sqlite.model.databaseType).toBe('SQLite')
    expect(sqlite.model.tables[0].fields.map((f) => [f.name, f.type, f.increment, f.defaultValue])).toEqual([
      ['id', 'integer', true, null],
      ['body', 'text', false, null],
      ['done', 'integer', false, 'false'],
    ])
  })

  it('warns about what it can’t read and fails on files without tables', () => {
    const { warnings, model } = fromDrizzle(`export const a = pgTable('a', {
  id: integer('id').primaryKey(),
  geo: geography('geo'),
  other: integer('other').references(() => elsewhere.id),
})`)
    expect(model.tables[0].fields.map((f) => f.type)).toEqual(['integer', 'geography', 'integer'])
    expect(warnings).toEqual([
      'a.geo uses geography(), which isn’t a known column type; it was imported as geography.'.replace('’', "'"),
      "a.other references a table that isn't in this file.",
    ])
    expect(() => fromDrizzle('export const x = 1')).toThrow(/No Drizzle tables found/)
  })
})

describe('readDeclarations', () => {
  it('skips what it doesn’t understand and keeps going', () => {
    const decls = readDeclarations(`
const a = 1 + 2
let b = function () { return 1 }
const c: Foo<Bar> = { x: [1, 'two', \`three\`], 'y': -4, ...rest, [k]: 5, m() { return 'six' } } satisfies Foo
if (x) { const inner = 1 }
const d = /* note */ f(a)?.g<T>()!
`)
    expect(decls.map((d) => [d.name, d.init.t])).toEqual([
      ['a', 'opaque'],
      ['b', 'opaque'],
      ['c', 'obj'],
      ['d', 'call'],
    ])
    expect(decls[2].init).toEqual({
      t: 'obj',
      props: [
        { key: 'x', value: { t: 'arr', items: [{ t: 'num', value: 1 }, { t: 'str', value: 'two' }, { t: 'tpl', tag: null, raw: 'three' }] } },
        { key: 'y', value: { t: 'num', value: -4 } },
        { key: 'm', value: { t: 'arrow', params: [], body: { t: 'str', value: 'six' } } },
      ],
    })
  })
})
