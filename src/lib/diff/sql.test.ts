import { describe, expect, it } from 'vitest'
import { parseModel } from '@/lib/dbml/compile'
import { SAMPLE_DBML } from '@/lib/sample'
import { generateMigration, sqlDefault } from './sql'
import type { MigrationDialect } from './sql'

const parse = (source: string) => {
  const r = parseModel(source)
  if (!r.model) throw new Error(r.diagnostics.map((d) => `${d.line}: ${d.message}`).join('\n'))
  return r.model
}

const migrate = (from: string, to: string, dialect: MigrationDialect = 'postgres') => generateMigration(parse(from), parse(to), dialect)

/** statements only, without comments or blank lines */
const statements = (sql: string) =>
  sql
    .split('\n')
    .filter((l) => l.trim() && !l.startsWith('--'))
    .join('\n')

const USERS = `Table users {
  id integer [pk, increment]
  email varchar(255) [unique, not null]
}`

describe('generateMigration: PostgreSQL', () => {
  it('says so when nothing changed', () => {
    const m = migrate(SAMPLE_DBML, SAMPLE_DBML)
    expect(m.up).toContain('-- No schema changes.')
    expect(statements(m.up)).toBe('')
    expect(statements(m.down)).toBe('')
  })

  it('creates a new table with keys, defaults and indexes, and drops it going down', () => {
    const to = `${USERS}
Table posts {
  id bigint [pk, increment]
  author_id integer [not null, ref: > users.id]
  title varchar(200) [not null, default: 'It\\'s new']
  published boolean [default: false]
  created_at timestamp [default: \`now()\`]
  indexes {
    (author_id, created_at)
    title [unique, name: 'posts_title_uq']
  }
}`
    const m = migrate(USERS, to)
    expect(statements(m.up)).toBe(`BEGIN;
CREATE TABLE "posts" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
  "author_id" integer NOT NULL,
  "title" varchar(200) NOT NULL DEFAULT 'It''s new',
  "published" boolean DEFAULT false,
  "created_at" timestamp DEFAULT (now()),
  PRIMARY KEY ("id")
);
CREATE INDEX "posts_author_id_created_at_idx" ON "posts" ("author_id", "created_at");
CREATE UNIQUE INDEX "posts_title_uq" ON "posts" ("title");
ALTER TABLE "posts" ADD CONSTRAINT "posts_author_id_fkey" FOREIGN KEY ("author_id") REFERENCES "users" ("id");
COMMIT;`)
    expect(statements(m.down)).toBe(`BEGIN;
ALTER TABLE "posts" DROP CONSTRAINT "posts_author_id_fkey";
DROP TABLE "posts";
COMMIT;`)
    expect(m.down).toContain('-- WARNING: destructive. Drops table "posts" and all of its rows.\nDROP TABLE "posts";')
  })

  it('adds, drops and alters columns', () => {
    const to = `Table users {
  id integer [pk, increment]
  email text [not null, default: '']
  nickname varchar(40) [unique]
}`
    const { up } = migrate(`${USERS.replace('}', '  age int [not null]\n}')}`, to)
    expect(statements(up)).toBe(`BEGIN;
ALTER TABLE "users" DROP CONSTRAINT "users_email_key";
ALTER TABLE "users" DROP COLUMN "age";
ALTER TABLE "users" ADD COLUMN "nickname" varchar(40) UNIQUE;
ALTER TABLE "users" ALTER COLUMN "email" TYPE text USING "email"::text;
ALTER TABLE "users" ALTER COLUMN "email" SET DEFAULT '';
COMMIT;`)
    expect(up).toContain('-- WARNING: destructive. Drops column "age" and its data.')
    expect(up).toContain('-- REVIEW: changes the type of "email" from varchar(255) to text.')
  })

  it('warns about a new not-null column with no default', () => {
    const { up } = migrate(USERS, USERS.replace('}', '  age int [not null]\n}'))
    expect(up).toContain('-- REVIEW: "age" is not null with no default, so this fails if "users" already has rows.\nALTER TABLE "users" ADD COLUMN "age" int NOT NULL;')
  })

  it('handles null, unique and identity changes both ways', () => {
    const from = 'Table t {\n  id int [pk]\n  code varchar(10)\n}'
    const to = 'Table t {\n  id int [pk, increment]\n  code varchar(10) [not null, unique]\n}'
    const m = migrate(from, to)
    expect(statements(m.up)).toBe(`BEGIN;
ALTER TABLE "t" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE "t" ALTER COLUMN "code" SET NOT NULL;
ALTER TABLE "t" ADD CONSTRAINT "t_code_key" UNIQUE ("code");
COMMIT;`)
    expect(statements(m.down)).toBe(`BEGIN;
ALTER TABLE "t" DROP CONSTRAINT "t_code_key";
ALTER TABLE "t" ALTER COLUMN "id" DROP IDENTITY IF EXISTS;
ALTER TABLE "t" ALTER COLUMN "code" DROP NOT NULL;
COMMIT;`)
  })

  it('renames tables and keeps their relationships', () => {
    const from = `${USERS}\nTable posts {\n  id int [pk]\n  author_id integer [ref: > users.id]\n}`
    const to = from.replace('Table users', 'Table accounts').replace('users.id', 'accounts.id')
    const m = migrate(from, to)
    expect(statements(m.up)).toBe('BEGIN;\nALTER TABLE "users" RENAME TO "accounts";\nCOMMIT;')
    expect(statements(m.down)).toBe('BEGIN;\nALTER TABLE "accounts" RENAME TO "users";\nCOMMIT;')
  })

  it('replaces the primary key', () => {
    const m = migrate('Table t {\n  a int [pk]\n  b int\n}', 'Table t {\n  a int\n  b int\n  indexes {\n    (a, b) [pk]\n  }\n}')
    expect(statements(m.up)).toBe('BEGIN;\nALTER TABLE "t" DROP CONSTRAINT "t_pkey";\nALTER TABLE "t" ADD PRIMARY KEY ("a", "b");\nCOMMIT;')
  })

  it('creates and drops indexes, including expressions and methods', () => {
    const m = migrate('Table t {\n  a text\n  indexes {\n    a\n  }\n}', 'Table t {\n  a text\n  indexes {\n    `lower(a)` [type: hash]\n  }\n}')
    expect(statements(m.up)).toBe('BEGIN;\nDROP INDEX "t_a_idx";\nCREATE INDEX "t_expr_idx" ON "t" USING HASH ((lower(a)));\nCOMMIT;')
  })

  it('adds enum values outside the transaction', () => {
    const from = 'Enum status {\n  draft\n}\nTable t {\n  s status\n}'
    const { up } = migrate(from, from.replace('  draft\n', '  draft\n  live\n'))
    expect(statements(up)).toBe(`ALTER TYPE "status" ADD VALUE 'live';\nBEGIN;\nCOMMIT;`)
  })

  it('rebuilds an enum type to remove a value', () => {
    const from = "Enum status {\n  draft\n  live\n  gone\n}\nTable t {\n  s status [default: 'draft']\n}"
    const { up } = migrate(from, from.replace('  gone\n', ''))
    expect(up).toContain(`-- WARNING: destructive. Removes 'gone' from enum "status".`)
    expect(statements(up)).toBe(`BEGIN;
ALTER TYPE "status" RENAME TO "status_old";
CREATE TYPE "status" AS ENUM ('draft', 'live');
ALTER TABLE "t" ALTER COLUMN "s" DROP DEFAULT;
ALTER TABLE "t" ALTER COLUMN "s" TYPE "status" USING "s"::text::"status";
ALTER TABLE "t" ALTER COLUMN "s" SET DEFAULT 'draft';
DROP TYPE "status_old";
COMMIT;`)
  })

  it('creates enum types before the tables that use them, and drops them after', () => {
    const to = 'Enum mood {\n  happy\n  sad\n}\nTable t {\n  id int [pk]\n  m mood\n}'
    const m = migrate('Table t {\n  id int [pk]\n}', to)
    expect(statements(m.up)).toBe(`BEGIN;
CREATE TYPE "mood" AS ENUM ('happy', 'sad');
ALTER TABLE "t" ADD COLUMN "m" "mood";
COMMIT;`)
    expect(statements(m.down)).toBe('BEGIN;\nALTER TABLE "t" DROP COLUMN "m";\nDROP TYPE "mood";\nCOMMIT;')
  })

  it('writes delete and update rules, and drops relationships before tables', () => {
    const from = `${USERS}\nTable posts {\n  id int [pk]\n  author_id integer\n}`
    const to = `${from}\nRef fk_author: posts.author_id > users.id [delete: set null, update: cascade]`
    const m = migrate(from, to)
    expect(statements(m.up)).toContain(
      'ALTER TABLE "posts" ADD CONSTRAINT "fk_author" FOREIGN KEY ("author_id") REFERENCES "users" ("id") ON DELETE SET NULL ON UPDATE CASCADE;',
    )
    const drop = migrate(to, USERS).up
    expect(drop.indexOf('DROP CONSTRAINT "fk_author"')).toBeLessThan(drop.indexOf('DROP TABLE "posts"'))
  })

  it('skips many-to-many relationships with a note', () => {
    const base = 'Table a {\n  id int [pk]\n}\nTable b {\n  id int [pk]\n}'
    const { up } = migrate(base, `${base}\nRef: a.id <> b.id`)
    expect(up).toContain('-- Skipped many-to-many relationship a.id → b.id')
    expect(statements(up)).toBe('BEGIN;\nCOMMIT;')
  })

  it('quotes schemas and odd names', () => {
    const { up } = migrate('Table x { id int }', 'Table x { id int }\nTable auth."user list" {\n  "the id" int [pk]\n}')
    expect(up).toContain('CREATE TABLE "auth"."user list" (\n  "the id" int,\n  PRIMARY KEY ("the id")\n);')
  })

  it('migrates the sample schema to an empty one and back', () => {
    const m = migrate(SAMPLE_DBML, 'Table placeholder { id int }')
    for (const t of ['customers', 'orders', 'order_items', 'books', 'publishers', 'authors', 'book_authors']) {
      expect(m.up).toContain(`DROP TABLE "${t}";`)
      expect(m.down).toContain(`CREATE TABLE "${t}" (`)
    }
    expect(m.down).toContain('CREATE TYPE "order_status" AS ENUM (\'pending\', \'paid\', \'shipped\', \'cancelled\');')
    expect(m.down).toContain('PRIMARY KEY ("order_id", "book_id")')
    // relationships come last, after every table exists
    expect(m.down.lastIndexOf('CREATE TABLE')).toBeLessThan(m.down.indexOf('FOREIGN KEY'))
  })
})

describe('generateMigration: MySQL', () => {
  it('uses MODIFY COLUMN with the full definition', () => {
    const { up } = migrate(USERS, USERS.replace('varchar(255) [unique, not null]', 'varchar [unique, default: "x"]'), 'mysql')
    expect(statements(up)).toBe("ALTER TABLE `users` MODIFY COLUMN `email` varchar(255) DEFAULT 'x';")
    expect(up).not.toContain('BEGIN')
  })

  it('creates tables with AUTO_INCREMENT and inline enums', () => {
    const to = 'Enum mood {\n  happy\n  "it\'s fine"\n}\nTable t {\n  id int [pk, increment]\n  m mood [not null]\n}'
    const { up } = migrate('Table x { id int }', `Table x { id int }\n${to}`, 'mysql')
    expect(statements(up)).toBe("CREATE TABLE `t` (\n  `id` int AUTO_INCREMENT,\n  `m` ENUM('happy', 'it''s fine') NOT NULL,\n  PRIMARY KEY (`id`)\n);")
  })

  it('changes enum columns when the enum changes', () => {
    const from = 'Enum status {\n  draft\n  live\n}\nTable t {\n  s status\n}'
    const m = migrate(from, from.replace('  live\n', '  live\n  archived\n'), 'mysql')
    expect(statements(m.up)).toBe("ALTER TABLE `t` MODIFY COLUMN `s` ENUM('draft', 'live', 'archived');")
    expect(m.down).toContain("-- WARNING: destructive. Removes 'archived' from enum status")
    expect(statements(m.down)).toBe("ALTER TABLE `t` MODIFY COLUMN `s` ENUM('draft', 'live');")
  })

  it('uses MySQL names for keys, unique constraints and indexes', () => {
    const from = 'Table t {\n  a int [pk]\n  b int [unique]\n  c int\n  indexes {\n    c\n  }\n}'
    const to = 'Table t {\n  a int\n  b int\n  c int\n  indexes {\n    (a, b) [pk]\n  }\n}'
    expect(statements(migrate(from, to, 'mysql').up)).toBe(`DROP INDEX \`c\` ON \`t\`;
ALTER TABLE \`t\` DROP INDEX \`b\`;
ALTER TABLE \`t\` DROP PRIMARY KEY;
ALTER TABLE \`t\` ADD PRIMARY KEY (\`a\`, \`b\`);`)
  })

  it('renames with RENAME TABLE and flags guessed foreign key names', () => {
    const from = `${USERS}\nTable posts {\n  id int [pk]\n  author_id integer [ref: > users.id]\n}`
    expect(statements(migrate(from, from.replace('Table users', 'Table people').replace('users.id', 'people.id'), 'mysql').up)).toBe('RENAME TABLE `users` TO `people`;')
    const { up } = migrate(from, USERS, 'mysql')
    expect(up).toContain('-- REVIEW: MySQL names unnamed foreign keys like posts_ibfk_1.')
    expect(up).toContain('ALTER TABLE `posts` DROP FOREIGN KEY `posts_author_id_fkey`;')
  })
})

describe('sqlDefault', () => {
  it('turns DBML defaults into SQL', () => {
    expect(sqlDefault("'a'")).toBe("'a'")
    expect(sqlDefault("'it's'")).toBe("'it''s'")
    expect(sqlDefault('`now()`')).toBe('(now())')
    expect(sqlDefault('42')).toBe('42')
    expect(sqlDefault('true')).toBe('true')
  })
})
