import type { EnumModel, FieldModel, IndexModel, RefModel, SchemaModel, TableModel } from '@/lib/dbml/types'
import { describeRef } from './summary'
import { diffSchemas, invertDiff, isEmptyDiff, isManyToMany, primaryKeyOf } from './schema'
import type { DiffOptions, SchemaDiff } from './schema'

export type MigrationDialect = 'postgres' | 'mysql'

export interface Migration {
  diff: SchemaDiff
  up: string
  down: string
}

export const DIALECT_LABEL: Record<MigrationDialect, string> = { postgres: 'PostgreSQL', mysql: 'MySQL' }

interface Named {
  schema: string | null
  name: string
}

/** Turns one direction of a diff into SQL. `target` is the schema the script migrates to. */
class Writer {
  private blocks: string[][] = []
  private block: string[] = []

  readonly dialect: MigrationDialect
  readonly target: SchemaModel

  constructor(dialect: MigrationDialect, target: SchemaModel) {
    this.dialect = dialect
    this.target = target
  }

  /* ---------- output ---------- */

  line(s: string) {
    this.block.push(s)
  }
  warn(s: string) {
    this.line(`-- WARNING: ${s}`)
  }
  review(s: string) {
    this.line(`-- REVIEW: ${s}`)
  }
  /** start a new group of statements, separated by a blank line */
  gap() {
    if (this.block.length) this.blocks.push(this.block)
    this.block = []
  }
  text(): string {
    this.gap()
    return this.blocks.map((b) => b.join('\n')).join('\n\n')
  }

  /* ---------- names ---------- */

  get pg() {
    return this.dialect === 'postgres'
  }
  q(name: string): string {
    return this.pg ? `"${name.replaceAll('"', '""')}"` : `\`${name.replaceAll('`', '``')}\``
  }
  table(t: Named): string {
    return t.schema ? `${this.q(t.schema)}.${this.q(t.name)}` : this.q(t.name)
  }
  /** a table from a relationship endpoint, which only has its id ("schema.table" or "table") */
  tableById(id: string): Named {
    const known = this.target.tables.find((t) => t.id === id)
    if (known) return known
    const dot = id.indexOf('.')
    return dot > 0 ? { schema: id.slice(0, dot), name: id.slice(dot + 1) } : { schema: null, name: id }
  }
  cols(names: string[]): string {
    return names.map((c) => (c.startsWith('`') && c.endsWith('`') ? (this.pg ? `(${c.slice(1, -1)})` : `((${c.slice(1, -1)}))`) : this.q(c))).join(', ')
  }

  /* default constraint names, matching what each database picks on its own */
  pkName(t: Named) {
    return `${t.name}_pkey`
  }
  uniqueName(t: Named, column: string) {
    return this.pg ? `${t.name}_${column}_key` : column
  }
  indexName(t: Named, i: IndexModel) {
    if (i.name) return i.name
    const parts = i.columns.map((c) => (c.startsWith('`') ? 'expr' : c))
    return this.pg ? `${t.name}_${parts.join('_')}_idx` : i.columns[0]?.startsWith('`') ? 'functional_index' : (parts[0] ?? 'idx')
  }
  fkName(r: RefModel) {
    return r.name ?? `${this.tableById(r.source.tableId).name}_${r.source.fields.join('_')}_fkey`
  }

  /* ---------- column definitions ---------- */

  enumFor(f: FieldModel): EnumModel | undefined {
    if (!f.enumName) return undefined
    return this.target.enums.find((e) => e.name === f.enumName && (e.schema ? f.type === `${e.schema}.${e.name}` : true))
  }

  type(f: FieldModel): string {
    if (this.pg) {
      if (f.increment) {
        const t = f.type.toUpperCase()
        if (['BIGINT', 'INT', 'INTEGER', 'SMALLINT'].includes(t)) return `${t} GENERATED BY DEFAULT AS IDENTITY`
        return ['SMALLSERIAL', 'SERIAL', 'BIGSERIAL'].includes(t) ? t : 'SERIAL'
      }
      return f.enumName ? f.type.split('.').map((p) => this.q(p)).join('.') : f.type
    }
    const e = this.enumFor(f)
    if (e) return `ENUM(${e.values.map(literal).join(', ')})`
    return f.type.toLowerCase() === 'varchar' ? 'varchar(255)' : f.type
  }

  /** the type to cast to in Postgres, without identity/serial wording */
  castType(f: FieldModel): string {
    return f.enumName ? f.type.split('.').map((p) => this.q(p)).join('.') : f.type
  }

  columnDef(f: FieldModel, opts: { unique: boolean }): string {
    const parts = [this.q(f.name), this.type(f)]
    if (f.notNull) parts.push('NOT NULL')
    if (f.defaultValue !== null) parts.push(`DEFAULT ${sqlDefault(f.defaultValue)}`)
    if (!this.pg && f.increment) parts.push('AUTO_INCREMENT')
    if (opts.unique && f.unique) parts.push('UNIQUE')
    return parts.join(' ')
  }

  /* ---------- statements ---------- */

  createTable(t: TableModel) {
    const body = t.fields.map((f) => `  ${this.columnDef(f, { unique: true })}`)
    const pk = primaryKeyOf(t)
    if (pk.length) body.push(`  PRIMARY KEY (${this.cols(pk)})`)
    this.line(`CREATE TABLE ${this.table(t)} (\n${body.join(',\n')}\n);`)
    for (const i of t.indexes) if (!i.pk) this.createIndex(t, i)
  }

  createIndex(t: Named, i: IndexModel) {
    const name = this.q(this.indexName(t, i))
    const unique = i.unique ? 'UNIQUE ' : ''
    if (this.pg) this.line(`CREATE ${unique}INDEX ${name} ON ${this.table(t)}${i.type ? ` USING ${i.type.toUpperCase()}` : ''} (${this.cols(i.columns)});`)
    else this.line(`CREATE ${unique}INDEX ${name} ON ${this.table(t)} (${this.cols(i.columns)})${i.type ? ` USING ${i.type.toUpperCase()}` : ''};`)
  }

  dropIndex(t: Named, i: IndexModel) {
    const name = this.indexName(t, i)
    if (this.pg) this.line(`DROP INDEX ${this.table({ schema: t.schema, name })};`)
    else this.line(`DROP INDEX ${this.q(name)} ON ${this.table(t)};`)
  }

  addRef(r: RefModel) {
    if (isManyToMany(r)) {
      this.line(`-- Skipped many-to-many relationship ${describeRef(r)}: it needs a join table, which this generator doesn't create.`)
      return
    }
    const child = this.tableById(r.source.tableId)
    const parent = this.tableById(r.target.tableId)
    let s = `ALTER TABLE ${this.table(child)} ADD CONSTRAINT ${this.q(this.fkName(r))} FOREIGN KEY (${this.cols(r.source.fields)}) REFERENCES ${this.table(parent)} (${this.cols(r.target.fields)})`
    if (r.onDelete) s += ` ON DELETE ${r.onDelete.toUpperCase()}`
    if (r.onUpdate) s += ` ON UPDATE ${r.onUpdate.toUpperCase()}`
    this.line(`${s};`)
  }

  dropRef(r: RefModel) {
    if (isManyToMany(r)) return
    const child = this.table(this.tableById(r.source.tableId))
    const name = this.q(this.fkName(r))
    if (this.pg) {
      this.line(`ALTER TABLE ${child} DROP CONSTRAINT ${name};`)
      return
    }
    if (!r.name) this.review(`MySQL names unnamed foreign keys like ${this.tableById(r.source.tableId).name}_ibfk_1. Check SHOW CREATE TABLE ${child} and fix the name below.`)
    this.line(`ALTER TABLE ${child} DROP FOREIGN KEY ${name};`)
  }
}

/* ---------- helpers ---------- */

const literal = (s: string) => `'${s.replaceAll("'", "''")}'`

/** DBML default (as the parser formats it) → SQL. */
export function sqlDefault(v: string): string {
  if (v.length >= 2 && v.startsWith('`') && v.endsWith('`')) return `(${v.slice(1, -1)})`
  if (v.length >= 2 && v.startsWith("'") && v.endsWith("'")) return literal(v.slice(1, -1))
  return v
}

/* ---------- rendering ---------- */

export function renderMigration(d: SchemaDiff, target: SchemaModel, dialect: MigrationDialect, opts: { title?: string; direction?: 'up' | 'down' } = {}): string {
  const w = new Writer(dialect, target)
  const pg = dialect === 'postgres'
  const direction = opts.direction ?? 'up'

  w.line(`-- ${opts.title ? `${opts.title} (${direction})` : direction === 'up' ? 'Up migration' : 'Down migration'}`)
  w.line(`-- ${DIALECT_LABEL[dialect]} script generated by Schemasketch. Review it before running it.`)
  if (isEmptyDiff(d)) {
    w.line('-- No schema changes.')
    return `${w.text()}\n`
  }
  w.line(`-- Constraint and index names follow ${DIALECT_LABEL[dialect]}'s defaults; adjust them if your database named them differently.`)
  if (!pg) w.line('-- MySQL commits each schema change on its own: if a statement fails, the ones before it stay applied.')
  w.gap()

  // Postgres can't use a new enum value in the transaction that adds it, so those go first
  const valueOnly = d.changedEnums.filter((e) => e.addedValues.length && !e.removedValues.length)
  if (pg && valueOnly.length) {
    w.line('-- New enum values are added outside the transaction: Postgres can’t use them in the same one.')
    for (const e of valueOnly) for (const v of e.addedValues) w.line(`ALTER TYPE ${w.table(e.to)} ADD VALUE ${literal(v)};`)
    w.gap()
  }
  if (pg) {
    w.line('BEGIN;')
    w.gap()
  }

  // 1. relationships that go away, before the columns and tables they use
  for (const r of d.removedRefs) w.dropRef(r)
  w.gap()

  // 2. indexes, unique constraints and primary keys that change, under the old table names
  for (const c of d.changedTables) {
    for (const i of c.removedIndexes) w.dropIndex(c.from, i)
    for (const cc of c.changedColumns) {
      if (!cc.attrs.includes('unique') || cc.to.unique) continue
      if (pg) w.line(`ALTER TABLE ${w.table(c.from)} DROP CONSTRAINT ${w.q(w.uniqueName(c.from, cc.from.name))};`)
      else w.line(`ALTER TABLE ${w.table(c.from)} DROP INDEX ${w.q(w.uniqueName(c.from, cc.from.name))};`)
    }
    if (c.primaryKey?.from.length) {
      if (pg) w.line(`ALTER TABLE ${w.table(c.from)} DROP CONSTRAINT ${w.q(w.pkName(c.from))};`)
      else w.line(`ALTER TABLE ${w.table(c.from)} DROP PRIMARY KEY;`)
    }
  }
  w.gap()

  // 3. renames
  for (const c of d.changedTables) {
    if (!c.renamed) continue
    if (pg) w.line(`ALTER TABLE ${w.table(c.from)} RENAME TO ${w.q(c.to.name)};`)
    else w.line(`RENAME TABLE ${w.table(c.from)} TO ${w.table(c.to)};`)
  }
  w.gap()

  // 4. new enum types (Postgres; MySQL enums live on the columns)
  if (pg) for (const e of d.addedEnums) w.line(`CREATE TYPE ${w.table(e)} AS ENUM (${e.values.map(literal).join(', ')});`)
  w.gap()

  // 5. tables that go away
  for (const t of d.removedTables) {
    w.warn(`destructive. Drops table ${w.table(t)} and all of its rows.`)
    w.line(`DROP TABLE ${w.table(t)};`)
  }
  w.gap()

  // 6. new tables
  for (const t of d.addedTables) {
    w.createTable(t)
    w.gap()
  }

  // 7. column changes
  const modified = new Set<string>()
  for (const c of d.changedTables) {
    const t = w.table(c.to)
    for (const f of c.removedColumns) {
      w.warn(`destructive. Drops column ${w.q(f.name)} and its data.`)
      w.line(`ALTER TABLE ${t} DROP COLUMN ${w.q(f.name)};`)
    }
    for (const f of c.addedColumns) {
      if (f.notNull && f.defaultValue === null && !f.increment) w.review(`${w.q(f.name)} is not null with no default, so this fails if ${t} already has rows.`)
      w.line(`ALTER TABLE ${t} ADD COLUMN ${w.columnDef(f, { unique: true })};`)
      modified.add(`${c.to.id}.${f.name}`)
    }
    for (const { from, to, attrs } of c.changedColumns) {
      const col = w.q(to.name)
      if (attrs.includes('type')) w.review(`changes the type of ${col} from ${from.type} to ${to.type}. Existing values must convert, and may be cut short.`)
      if (attrs.includes('notNull') && to.notNull) w.review(`${col} becomes not null, so this fails if any row has a null there.`)
      if (!pg) {
        if (attrs.some((a) => a !== 'unique')) {
          w.line(`ALTER TABLE ${t} MODIFY COLUMN ${w.columnDef(to, { unique: false })};`)
          modified.add(`${c.to.id}.${to.name}`)
        }
        continue
      }
      if (attrs.includes('default') && to.defaultValue === null) w.line(`ALTER TABLE ${t} ALTER COLUMN ${col} DROP DEFAULT;`)
      if (attrs.includes('increment') && !to.increment) w.line(`ALTER TABLE ${t} ALTER COLUMN ${col} DROP IDENTITY IF EXISTS;`)
      if (attrs.includes('type')) w.line(`ALTER TABLE ${t} ALTER COLUMN ${col} TYPE ${w.castType(to)} USING ${col}::${w.castType(to)};`)
      if (attrs.includes('notNull')) w.line(`ALTER TABLE ${t} ALTER COLUMN ${col} ${to.notNull ? 'SET' : 'DROP'} NOT NULL;`)
      if (attrs.includes('default') && to.defaultValue !== null) w.line(`ALTER TABLE ${t} ALTER COLUMN ${col} SET DEFAULT ${sqlDefault(to.defaultValue)};`)
      if (attrs.includes('increment') && to.increment) w.line(`ALTER TABLE ${t} ALTER COLUMN ${col} ADD GENERATED BY DEFAULT AS IDENTITY;`)
    }
    w.gap()
  }

  // 8. enum value changes that touch existing columns
  const addedTableIds = new Set(d.addedTables.map((t) => t.id))
  for (const e of d.changedEnums) {
    const users: { table: TableModel; field: FieldModel }[] = []
    for (const table of target.tables)
      for (const field of table.fields) if (field.enumName === e.to.name && w.enumFor(field) === e.to) users.push({ table, field })

    if (!pg) {
      const existing = users.filter((u) => !addedTableIds.has(u.table.id))
      const todo = existing.filter((u) => !modified.has(`${u.table.id}.${u.field.name}`))
      if (e.removedValues.length && existing.length)
        w.warn(`destructive. Removes ${e.removedValues.map(literal).join(', ')} from enum ${e.to.name}; change rows that use them first, or MySQL rejects the change.`)
      for (const u of todo) w.line(`ALTER TABLE ${w.table(u.table)} MODIFY COLUMN ${w.columnDef(u.field, { unique: false })};`)
      w.gap()
      continue
    }
    if (!e.removedValues.length) continue
    const type = w.table(e.to)
    const old = w.table({ schema: e.to.schema, name: `${e.to.name}_old` })
    w.warn(`destructive. Removes ${e.removedValues.map(literal).join(', ')} from enum ${type}. Postgres can't drop enum values, so the type is rebuilt; change rows that use them first, or this fails.`)
    w.line(`ALTER TYPE ${type} RENAME TO ${w.q(`${e.to.name}_old`)};`)
    w.line(`CREATE TYPE ${type} AS ENUM (${e.to.values.map(literal).join(', ')});`)
    for (const { table, field } of users) {
      const t = w.table(table)
      const col = w.q(field.name)
      if (field.defaultValue !== null) w.line(`ALTER TABLE ${t} ALTER COLUMN ${col} DROP DEFAULT;`)
      w.line(`ALTER TABLE ${t} ALTER COLUMN ${col} TYPE ${type} USING ${col}::text::${type};`)
      if (field.defaultValue !== null) w.line(`ALTER TABLE ${t} ALTER COLUMN ${col} SET DEFAULT ${sqlDefault(field.defaultValue)};`)
    }
    w.line(`DROP TYPE ${old};`)
    w.gap()
  }

  // 9. primary keys, unique constraints and indexes under the new names
  for (const c of d.changedTables) {
    const t = w.table(c.to)
    if (c.primaryKey?.to.length) w.line(`ALTER TABLE ${t} ADD PRIMARY KEY (${w.cols(c.primaryKey.to)});`)
    for (const cc of c.changedColumns)
      if (cc.attrs.includes('unique') && cc.to.unique) w.line(`ALTER TABLE ${t} ADD CONSTRAINT ${w.q(w.uniqueName(c.to, cc.to.name))} UNIQUE (${w.q(cc.to.name)});`)
    for (const i of c.addedIndexes) w.createIndex(c.to, i)
  }
  w.gap()

  // 10. new relationships, once every table and column exists
  for (const r of d.addedRefs) w.addRef(r)
  w.gap()

  // 11. enum types nothing uses any more
  if (pg) for (const e of d.removedEnums) w.line(`DROP TYPE ${w.table(e)};`)
  w.gap()

  if (pg) w.line('COMMIT;')
  return `${w.text()}\n`
}

/** Diff two schemas and write the up and down scripts for one dialect. */
export function generateMigration(from: SchemaModel, to: SchemaModel, dialect: MigrationDialect, opts: DiffOptions & { title?: string } = {}): Migration {
  const diff = diffSchemas(from, to, opts)
  return {
    diff,
    up: renderMigration(diff, to, dialect, { title: opts.title, direction: 'up' }),
    down: renderMigration(invertDiff(diff), from, dialect, { title: opts.title, direction: 'down' }),
  }
}
